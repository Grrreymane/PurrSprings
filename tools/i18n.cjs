'use strict';
// Languages (src/core/i18n.js): the Chinese original and the translations bundled into the game.
//   node tools/i18n.cjs          write i18n/zh.json + zh.limits.json from the Chinese string literals in src/, then
//                                src/data/lang.js from i18n/{en,ja,ko,es}.json            (npm run i18n, before sync)
//   node tools/i18n.cjs --check  fail when zh.json or lang.js is stale; list missing translations   (npm test)
// Keys are the Chinese originals themselves (txt() looks every string up as it is drawn); templates use {0}, {1}.
// The 1GP upload (upload_game_text) takes i18n/zh.json as the original and the four files as translations.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const TARGETS = ['en', 'ja', 'ko', 'es'];
const SKIP = new Set(['万']);   // fmt()'s own unit, never drawn alone (i18n.js picks 万 / 만 / K)
const META = { 'meta.title': '猫猫温泉旅馆' };
const HAN = /[㐀-鿿豈-﫿]/;
const wide = c => /[ᄀ-ᅟ⺀-꓏가-힣豈-﫿︰-﹏＀-｠￠-￦]/.test(c);
const width = s => [...s].reduce((n, c) => n + (wide(c) ? 2 : 1), 0);

// the string literals of a source file (comments skipped; quotes inside regex literals are not expected here)
function literals(text) {
  const out = [];
  for (let i = 0; i < text.length; i++) {
    const c = text[i], d = text[i + 1];
    if (c === '/' && d === '/') { i = text.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && d === '*') { i = text.indexOf('*/', i + 2) + 1; if (i <= 0) break; continue; }
    if (c !== "'" && c !== '"' && c !== '`') continue;
    let j = i + 1, raw = '';
    while (j < text.length && text[j] !== c) { if (text[j] === '\\') { raw += text[j] + text[j + 1]; j += 2; } else raw += text[j++]; }
    if (c !== '`') out.push(JSON.parse('"' + raw.replace(/\\'/g, "'").replace(/"/g, '\\"').replace(/\\\\"/g, '\\"') + '"'));
    i = j;
  }
  return out;
}
function original() {
  const mods = JSON.parse(fs.readFileSync(path.join(root, 'src/modules.json'), 'utf8')).filter(f => f !== 'src/data/lang.js');
  const zh = {};
  for (const f of mods) for (const s of literals(fs.readFileSync(path.join(root, f), 'utf8'))) if (HAN.test(s) && !SKIP.has(s) && !(s in zh)) zh[s] = s;
  return Object.assign({}, META, zh);
}
// display width limits (CJK 2, else 1): short labels sit in buttons, pills and rows, so they get little slack;
// longer lines (speech bubbles, cards) may run about half as long again
function limits(zh) {
  const o = { '*': 80 };
  for (const k in zh) { const w = width(zh[k]); o[k] = w <= 12 ? w + 2 : Math.ceil(w * 1.5); }
  return o;
}
const json = o => JSON.stringify(o, null, 1).replace(/^ /gm, '  ') + '\n';
function langJs() {
  const data = {};
  for (const l of TARGETS) {
    const f = path.join(root, 'i18n', l + '.json');
    const d = fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {};
    data[l] = {}; for (const k in d) if (!k.startsWith('meta.') && typeof d[k] === 'string' && d[k]) data[l][k] = d[k];
  }
  return '// ============================================================ translations (generated by tools/i18n.cjs from i18n/*.json - do not edit)\n' +
    '// Chinese original -> text, for src/core/i18n.js. Edit i18n/<lang>.json, then npm run i18n and npm run sync.\n' +
    'const LANG_DATA = {\n' + TARGETS.map(l => '  ' + l + ': {\n' + Object.keys(data[l]).map(k => '    ' + JSON.stringify(k) + ': ' + JSON.stringify(data[l][k]) + ',').join('\n') + '\n  },').join('\n') + '\n};\n';
}
const zh = original(), files = [['i18n/zh.json', json(zh)], ['i18n/zh.limits.json', json(limits(zh))]];
// the 1GP upload copy (upload_game_text use "phrases"): 1GP keys must be ASCII, so each original becomes
// p.<SHA-256 of the trimmed original>; i18n.js langFetch hashes the same way to map the author's edits back
{
  const pid = s => 'p.' + require('node:crypto').createHash('sha256').update(s.trim(), 'utf8').digest('hex');
  const ids = new Map(); for (const k in zh) if (!k.startsWith('meta.')) { const id = pid(k); if (ids.has(id)) throw Error('Two originals trim to the same text: ' + k); ids.set(id, k); }
  const by = d => { const o = {}; for (const [id, k] of ids) if (typeof d[k] === 'string' && d[k]) o[id] = d[k]; return o; };
  const lim = limits(zh), pl = { '*': lim['*'] }; for (const [id, k] of ids) pl[id] = lim[k];
  files.push(['i18n/phrases/zh.json', json(by(zh))], ['i18n/phrases/zh.limits.json', json(pl)]);
  for (const l of TARGETS) { const f = path.join(root, 'i18n', l + '.json'); if (fs.existsSync(f)) files.push(['i18n/phrases/' + l + '.json', json(by(JSON.parse(fs.readFileSync(f, 'utf8'))))]); }
}
const check = process.argv.includes('--check');
const stale = [];
for (const [f, text] of files) {
  const p = path.join(root, f), now = fs.existsSync(p) ? fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : null;
  if (now === text) continue;
  if (check) stale.push(f); else { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); }
}
{
  const p = path.join(root, 'src/data/lang.js'), text = langJs(), now = fs.existsSync(p) ? fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : null;
  if (now !== text) { if (check) stale.push('src/data/lang.js'); else fs.writeFileSync(p, text); }
}
const keys = Object.keys(zh), report = [];
for (const l of TARGETS) {
  const f = path.join(root, 'i18n', l + '.json'), d = fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {};
  const miss = keys.filter(k => typeof d[k] !== 'string' || !d[k]), extra = Object.keys(d).filter(k => !(k in zh));
  report.push(`${l}: ${keys.length - miss.length}/${keys.length}` + (miss.length ? `, missing ${miss.length} (first: ${miss.slice(0, 3).join(' | ')})` : '') + (extra.length ? `, ${extra.length} unused` : ''));
}
if (stale.length) { console.error('Stale language files (run npm run i18n, then npm run sync): ' + stale.join(', ')); process.exitCode = 1; }
else console.log((check ? 'Languages up to date. ' : 'Wrote i18n/zh.json, zh.limits.json, src/data/lang.js. ') + keys.length + ' texts; ' + report.join('; '));
